"""Разбор строки подключения там, где от имени базы зависит отказ.

Модуль ничего не читает из окружения и не тянет тяжёлых зависимостей, поэтому
его можно подключить до подмены env-переменных — в отличие от `config`, который
на импорте строит настройки.

Зачем отдельный файл. И `testsupport.py` (не дать pytest отработать TRUNCATE по
чужой базе), и `scripts/gate.sh` (не дать alembic замигрировать продакшн)
сверяли имя, взятое из строки как попало, — «последний отрезок после слэша».
Это не имя, а хвост строки: `?sslmode=require` (в таком виде строку отдают
Railway, Supabase и Neon) приклеивается к нему, хвостовой слэш оставляет
пустоту, а URL без пути открывает базу с именем пользователя, которая тоже
кончается на слэш. Запрет, который обходят такие написания, — не запрет,
поэтому обе реализации сверяются на одной таблице форм в
`test_local_gate_parity.py`.
"""

from urllib.parse import urlsplit


def database_name(url: str) -> str:
    """Имя базы, которое реально откроет драйвер, или пустая строка.

    Пустой путь — не «базы нет»: asyncpg подставляет вместо неё имя
    пользователя, поэтому без пути возвращается оно. Якорь и параметры
    urlsplit разбирает отдельно, им в имени места нет.
    """
    parts = urlsplit(url)
    name = parts.path.strip("/")
    return name or (parts.username or "")
