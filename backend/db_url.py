"""Разбор строки подключения там, где от имени базы зависит отказ.

Модуль ничего не читает из окружения и не тянет тяжёлых зависимостей, поэтому
его можно подключить до подмены env-переменных — в отличие от `config`, который
на импорте строит настройки.

Зачем отдельный файл. Прежняя разборка брала `urlsplit(url).path` и снимала с
него слэши все сразу, из-за чего миновала имя в обе стороны: строка
`.../%77ake` (такую форму отдают панели managed-постгреса) читалась как
«%77ake» и страж продакшна её не узнавал, а `...//wake`, наоборот, считался
продакшном, хотя драйвер открывает базу `/wake`. Ни то, ни другое не
чинится правкой «взять не тот отрезок»: имя надо читать так же, как его
читает диалект. То же правило второй раз живёт в bash (`scripts/gate.sh`),
где про раскодирование нельзя просто забыть, поэтому обе реализации сверяются
на одной таблице форм в `test_local_gate_parity.py`; там же стоит зеркало
«взять последний отрезок после слэша»: у такого разбора к имени приклеивается
`?sslmode=require` (в этом виде строку отдают Railway, Supabase и Neon), а
при пустом пути вместо имени выдаётся хост с портом.

Правило взято не из головы: оно сверено с тем же движком, который открывает
соединение (SQLAlchemy 2 и диалект asyncpg), — замеры лежат в таблице MEASURED
в `test_db_url.py` и там же перепроверяются прогоном самого диалекта. Разбор
оказывается проще, чем кажется по названию: имя — всё, что стоит после первого
слэша за authority, до первого `?`, снятым ровно одним слэшем и раскодированным
из percent-формы. Отсюда три неочевидности: `//wake` — это база `/wake`, а не
`wake`; `/wake/x_test` — база с косой чертой в имени, а не «wake»; якорь
драйвер от имени не отделяет, поэтому `#` остаётся внутри имени.

Раскодирование касается не только пути: то же имя в userinfo при пустом пути
(`postgresql+asyncpg://%77ake:pw@localhost:5432/`) старый разбор читал буквально,
страж продакшна его не узнавал, `alembic upgrade head` проходил, и драйвер
открывал базу `wake`.
"""

from urllib.parse import unquote


def database_name(url: str) -> str:
    """Имя базы, которое реально откроет драйвер, или пустая строка.

    Параметры (`?...`) в имя не входят, якорь (`#...`) — входит: диалект режет
    строку только по первому `?`. Снимается один ведущий слэш, не все, а
    раскодирование применяется к уже взятому отрезку, поэтому `%2F` остаётся
    символом внутри имени и не начинает новый путь.

    Пустой путь — не «базы нет»: asyncpg подставляет вместо неё имя
    пользователя, поэтому без пути возвращается оно (тоже раскодированное).
    """
    tail = url.partition("://")[2].partition("?")[0]
    authority, _, rest = tail.partition("/")
    name = unquote(rest)
    if name:
        return name
    return unquote(authority.rpartition("@")[0].partition(":")[0])
