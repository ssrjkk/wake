"""Хост ссылки-источника: разбор там, где от него зависит отказ.

Модуль ничего не читает из окружения и не тянет зависимостей, поэтому его можно
подключать и к валидации записи (predict_resolution), и к тому, что показывает
бот (telegram_bot). Правило одно, а спрашивают его двое: запись обязана быть
адресом, который действительно куда-то ведёт, а отказ должен звучать одинаково
с обеих сторон.

Почему разбор, а не `startswith("https://")` (формы замерены на urlsplit и на
`new URL(...)` в Node 24):

  * `https://good.com\\nX` — перевод строки внутри netloc исчезает при разборе, и
    хост получается `good.comx`. Префикс-проверка такую строку не видит вовсе:
    она смотрит только начало;
  * `https://t.me@evil.com` — префикс принимает, а открывается evil.com. Разбор
    как минимум называет хост правильно, и для ссылки на источник этого
    достаточно, чтобы отвергнуть userinfo;
  * `https://good.com:443x` — префикс принимает, а `parts.port` на этом же
    адресе бросает ValueError: порт не разобран, и ссылки нет;
  * `https:/good.com` и `https:example.com` — у urlsplit в обеих хоста нет
    (netloc пустой), а WHATWG «догадывается» и отдаёт `good.com`: на одной
    ошибке в написании два разбора показывают два разных адреса. Правило
    требует каноническое `scheme://`, и с этого места расхождений не остаётся;
  * `HTTPS://good.com` — валидный https, который префикс отвергает: доказательство
    резолюции молча перестаёт показываться из-за регистра.
"""

import re
from urllib.parse import urlsplit

# Ссылка обязана состоять из печатаемых ASCII: пробелы и переводы строк внутри
# атрибута, кавычки и угловые скобки ломают и HTML, и то, что по этому адресу
# реально откроется, а non-ASCII (включая bidir-символы) — способ показать
# одному читателю один домен, а другому другой. Punycode остаётся ASCII.
_UNSAFE = re.compile(r"""[\s<>"'`\\]|[^\x20-\x7e]""")
# Хост после разбора: только буквы, цифры, дефис и точки. Punycode (`xn--…`)
# под этот шаблон попадает, IPv6-литерал («::1») и любая строка с точкой с
# запятой или пробелом — нет.
_HOST = re.compile(r"^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$")


def source_host(url: object, https_only: bool = False) -> str:
    """Имя хоста ссылки-источника или пустая строка, если ссылкой она не является.

    Пустая строка — единственный честный ответ для `https://`, `https:/x`,
    `//evil.com` и `mailto:…`: хоста в них нет либо он не назван, а показывать
    такую «ссылку на источник» — вести читателя в никуда.

    `https_only` различает запись и показ: в базу куратор может положить и
    http-страницу, а бот подписывает ссылку только https — и то, и другое
    решается этим разбором, чтобы «валидный источник» не означал две разные
    вещи в зависимости от того, кто спрашивает.
    """
    text = str(url or "").strip()
    if not text or _UNSAFE.search(text):
        return ""
    try:
        parts = urlsplit(text)
        # `parts.port` бросает ValueError на «https://host:443x» и на порте вне
        # диапазона — проверять границы отдельно было бы мёртвым кодом. Нулевой
        # порт он пропускает, а по нему никуда не подключаются.
        port = parts.port
    except ValueError:
        return ""
    scheme = parts.scheme.lower()
    wanted = ("https",) if https_only else ("http", "https")
    if scheme not in wanted:
        return ""
    # userinfo меняет смысл адреса: до «@» — логин, а не домен.
    if parts.username is not None or parts.password is not None:
        return ""
    if port == 0:
        return ""
    host = (parts.hostname or "").lower()
    # Пустая этикетка («good..com») — не имя: адрес с ней не резолвится, и
    # принять её означало бы пообещать «хост назван», не пообещав ничего.
    if ".." in host:
        return ""
    return host if _HOST.match(host) else ""
