"""Что площадка ИСПОЛНИЛА по отправленной зеркальной заявке.

Чистая функция: ни HTTP, ни ключей, ни базы. Вход — уже разобранные строки
ленты `/api/v1/trades` (их форму разбирает lighter_rest.get_account_taker_fills),
выход — статус и исполненный базовый размер. Листенеру остаётся выбрать окно
повторов и записать исход в журнал, поэтому весь разбор сверки тестируется без
сети и без Lighter (test_mirror_fill.py).

Зачем этот файл вообще появился. `create_order` возвращает хэш заявки, а не
отчёт об исполнении, и MARKET+IOC, снятый с цены, отвечает УСПЕШНО. До этого
модуля журнал знал только «заявка принята площадкой» (`sent`), а учёт
`mirror_positions` двигался на ЗАКАЗАННЫЙ размер: IOC, который не исполнился
ни на одну сделку, оставлял подписчика с позицией, которой у него нет, и
следующий reduce планировался от числа листенера, а не от реальности.

Почему сверка возможна (замер mainnet 2026-11-16, не предположение):
  - `/api/v1/trades` отдаётся анонимно, а `account_index` + `market_id` +
    `role=taker` + `type=trade` сужают выборку до собственных тейкер-сделок
    подписчика (100 строк из 100 принадлежат запрошенному аккаунту; с
    role=taker в ответе нет ни одной мейкер-строки, с role=maker — ни одной
    тейкерской);
  - строка ленты несёт client order id каждой стороны (`ask_client_id`,
    `bid_client_id`), то есть тот самый `client_order_index`, который мы
    отправляли с заявкой;
  - `client_order_index` выводим из id строки mirror_log (см.
    build_order_args), поэтому он уникален на каждый замысел и не требует
    ни хэша сделки, ни окна по времени.

По последнему пункту этот файл и держит ключ атрибуции: `client_order_index`
здесь — единственная функция, из которой её берут и отправщик (listener), и
сверка. Разъездись они в двух местах, листенер не нашёл бы в ленте собственные
ордера, и каждый реальный филл выглядел бы снятым с цены.

Чего сверка НЕ видит. Ликвидации и deleverage (type != "trade") в учёт не
берутся осознанно: их размер — не исполнение зеркального ордера, и сложить его
значило бы записать подписчику позицию, которую он не заказывал. Рука самого
подписчика в том же рынке остаётся дрейфом, который листенер не замечает, —
сверка журнала с позициями аккаунта на Lighter для этого и следующая задача.
"""

import uuid
from dataclasses import dataclass
from decimal import Decimal


# Словарь исхода живой заявки. `sent` остаётся в журнале отдельно: он значит
# «заявка ушла, исполнение не сверялось» — строки, написанные до этого модуля,
# и процесс, умерший посреди сверки.
UNCONFIRMED = "unconfirmed"
FILLED = "filled"
PARTIALLY_FILLED = "partially_filled"
UNFILLED = "unfilled"


def client_order_index(order_uid: str) -> int:
    """Client order index зеркальной заявки по её id в mirror_log.

    Уникален на каждый замысел (uuid4) и умещается в int32, который ждёт
    Lighter. Одна функция на отправку и на сверку намеренно: две копии одной
    формулы разъехались бы молча, и сверка перестала бы находить собственные
    ордера, продолжая выглядеть зелёной."""
    return int(uuid.UUID(order_uid).int % 2**31)


@dataclass(frozen=True)
class FillReport:
    """Итог сверки: чем закончилась заявка и сколько базового актива исполнилось.

    `executed_base=None` — это «неизвестно», а не «ноль»: у первого нет права
    двигать учёт, у второго — тем более."""

    status: str
    executed_base: float | None
    reason: str | None


def fill_report(
    fills: list[dict],
    *,
    account_index: int,
    market_id: int,
    order_uid: str,
    ordered_base: float,
) -> FillReport:
    """Сколько исполнено ПО ЭТОЙ ЗАЯВКЕ из строк ленты, и как это назвать.

    Фильтр на каждой строке — поясной, а не недоверие эндпоинту: параметры
    запроса сузили ленту до наших тейкер-сделок в нашем рынке, но money path
    не должен полагаться на чужую реализацию фильтра. Строка чужого ордера,
    чужого рынка или чужой роли (подписчик стоял мейкером) в сумму не попадёт
    никогда.

    Сумма — в Decimal по str(): базовые размеры приходят с площадки строками
    вида "0.00089", и float-сложение дало бы 0.1 + 0.2 = 0.30000000000000004,
    то есть полное исполнение выглядело бы частичным, а учёт подписался бы
    числом, которого на площадке нет.
    """
    ours = client_order_index(order_uid)
    total = Decimal(0)
    for row in fills:
        if (
            row.get("market_id") != market_id
            or str(row.get("type")) != "trade"
            or row.get("taker_account_index") != account_index
            or row.get("taker_client_order_index") != ours
        ):
            continue
        size = row.get("size")
        if size is None:
            # Одна нечитаемая строка обесценивает всю сумму: отдать
            # вызывающему частичную сумму «по остальным строкам» значило бы
            # двинуть учёт на число, которое заведомо меньше реального.
            return FillReport(
                UNCONFIRMED,
                None,
                f"лента Lighter не даёт размер сделки "
                f"{row.get('trade_id')!r} — исполненное по заявке неизвестно",
            )
        total += Decimal(str(size))

    ordered = Decimal(str(ordered_base))
    if total == 0:
        # Числа в reason не дублируются: заказанный и исполненный размеры —
        # соседние колонки той же строки (base_amount, filled_base_amount), а
        # reason объясняет ПРИЧИНУ. Здесь он тем и полезен, что отличает «не
        # исполнилось» от «не прочитано»: у второго причины нет, есть сбой.
        return FillReport(
            UNFILLED,
            0.0,
            "IOC снят с цены: ни одной сделки по этой заявке",
        )
    executed = float(total)
    if total > ordered:
        # Больше заказанного IOC исполнить не может, поэтому лишнее — сбой
        # разбора или чужая заявка с нашим client order index. Учёт выше плана
        # не растёт, но расхождение обязано быть видно в журнале — и здесь
        # числа в тексте нужны: их не видно ни из одной колонки строки.
        return FillReport(
            FILLED,
            float(ordered),
            f"площадка сообщила {executed} исполненным против заказанных "
            f"{ordered_base} — учёт двинут по заказу",
        )
    if total == ordered:
        return FillReport(FILLED, executed, None)
    return FillReport(
        PARTIALLY_FILLED,
        executed,
        "IOC снят с цены на остатке: заявка исполнилась частично",
    )
